from playwright.sync_api import sync_playwright
errs=[]
def ok(c,m): print(("PASS " if c else "FAIL ")+m); (None if c else errs.append(m))
with sync_playwright() as p:
    b=p.chromium.launch()
    for vp,name in [({"width":1366,"height":768},"PC"),({"width":390,"height":844},"phone")]:
        ctx=b.new_context(viewport=vp,is_mobile=name=="phone",has_touch=name=="phone"); pg=ctx.new_page()
        pg.on("pageerror",lambda e:errs.append(str(e))); pg.on("console",lambda m: m.type=="error" and errs.append(m.text))
        pg.goto("http://127.0.0.1:8790/"); pg.wait_for_selector(".hfr-live:not(.hfr-off)",timeout=15000)
        pg.fill("input[type=search]","linezolid"); pg.wait_for_selector(".hfr-ans"); pg.wait_for_timeout(1700)
        pg.click(".hfr-ans .hfr-pri"); pg.wait_for_selector(".hfr-sheet.hfr-on"); pg.keyboard.press("Escape"); pg.wait_for_timeout(300)
        pg.fill("input[type=search]","qqzzxy"); pg.wait_for_timeout(1800)
        pg.click("button[aria-label='Open Hulool User Analytics']"); pg.wait_for_timeout(300)
        t=pg.inner_text("table"); print(" ",name,"log:",t.replace("\n"," | ")[:330])
        ok("Restrictions search" in t and "“linezolid” — 2 results" in t,name+": search row in Hulool log")
        ok("Restrictions look-up" in t and "LINEZOLID" in t,name+": look-up row in Hulool log")
        ok("no result" in t,name+": zero-result search logged")
        ok("Pharmacist A" in t,name+": user recorded")
        pg.screenshot(path=f"/home/claude/e2e/hostlog_{name}.png")
        pg.click("text=Close")
        pg.select_option("select[aria-label='Demo user']","admin"); pg.wait_for_selector(".hfr-gbtn:has-text('Admin')")
        pg.click(".hfr-gbtn:has-text('Admin')"); pg.wait_for_selector(".hfr-tabs")
        tabs=pg.inner_text(".hfr-tabs"); ok("Analytics" not in tabs,name+": no separate analytics tab ("+tabs.replace(chr(10),' ')+")")
        pg.click(".hfr-atool >> text=Add medicine"); pg.fill("#hfr-no","8900055555" if name=="PC" else "8900055556"); pg.fill("#hfr-name","HOSTLOG TEST 1 MG"); pg.click(".hfr-mf >> text=Add medicine"); pg.wait_for_timeout(600)
        pg.click("button[aria-label='Open Hulool User Analytics']"); pg.wait_for_timeout(300)
        t=pg.inner_text("table"); ok("Restrictions admin" in t and "Medicine added: HOSTLOG TEST 1 MG" in t and "Admin B" in t,name+": admin change in Hulool log")
